//! Turns `third_party/php-prelude/*.php` into one embedded table.
//!
//! Embedded rather than read from disk at runtime because the stubs have to be there for a user who
//! installed a single binary, and a language server that silently knows nothing about `strlen`
//! because a directory was missing is worse than one that fails loudly.

use std::{env, fs, path::PathBuf};

fn main() {
    let source = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../third_party/php-prelude")
        .canonicalize()
        .expect("the vendored prelude is part of the repository");

    println!("cargo::rerun-if-changed={}", source.display());

    let mut files: Vec<PathBuf> = fs::read_dir(&source)
        .expect("prelude directory is readable")
        .map(|entry| entry.expect("prelude entry is readable").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "php"))
        .collect();
    // Sorted so the generated table, and therefore the content hash, does not depend on the order
    // the filesystem happened to return.
    files.sort();

    let mut out = String::from(
        "/// Every stub file, as (file name, contents). Generated by `build.rs`.\n\
         pub(crate) const PRELUDE: &[(&str, &str)] = &[\n",
    );
    for path in &files {
        let name = path
            .file_name()
            .expect("a file has a name")
            .to_str()
            .expect("stub file names are ASCII");
        out.push_str(&format!(
            "    ({name:?}, include_str!({:?})),\n",
            path.display().to_string()
        ));
    }
    out.push_str("];\n");

    let generated =
        PathBuf::from(env::var_os("OUT_DIR").expect("cargo sets OUT_DIR")).join("prelude_table.rs");
    fs::write(&generated, out).expect("OUT_DIR is writable");
}
